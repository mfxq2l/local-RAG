"""RAG Prompt 模板。

Context 中的每一段都带 ``[n]`` 编号（见 :mod:`src.rag.context`），
Prompt 要求模型在回答里用同样的编号标注出处，前端再据此渲染引用卡片。
"""

from __future__ import annotations

SYSTEM_PROMPT = """你是一个严谨但务实的知识库助手。

必须遵守的规则：
1. **优先**依据【参考资料】回答；用到了资料就标注来源编号，例如 [1] 或 [2][3]。
2. 引用原始命令、代码、参数时保持原样，不要改写。
3. 参考资料里可能混有两种来源，注意区分：
   - **本地文档**：标为「来源：xxx.md」
   - **联网搜索**：标为「网页：标题 | 链接：https://...」
   引用联网结果时照常标注 [编号] 即可，**不要自己编造链接**。
4. **如果参考资料与问题无关、或不足以回答**：
   - 先用一句话说明"参考资料里没有直接依据"，**然后继续用你自己的知识尽力回答**；
   - 不要生硬拒答（不要只说"根据现有资料无法回答"就结束）；
   - 也不要把无关的资料硬凑成答案。
5. 用你自己的知识回答时，不要编造来源编号 —— 编号只用于真实引用到的资料。
6. 如果本地文档与联网结果**互相矛盾**，说明分歧并给出双方说法。
7. 用简体中文回答，条理清晰，避免空话。"""

USER_TEMPLATE = """【参考资料】
{context}

【问题】
{query}

请依据上述参考资料回答。
如果资料里没有直接依据，请先说明这一点，然后用你自己的知识继续回答，不要只回一句"无法回答"。
资料中若含联网搜索结果（标注为「网页：… | 链接：…」），可以一并采信并照常标注编号。"""


# ---------------------------------------------------------------------------
# 多轮对话
# ---------------------------------------------------------------------------

# 追问改写：把依赖上下文的问题变成独立可检索的查询。
#
# 这一步是多轮对话能用的前提 —— 「那第二点呢」直接拿去检索什么都找不到。
CONDENSE_PROMPT = """你是检索查询改写器。

任务：结合对话历史，把用户的最新问题改写成**一个不依赖上下文、可独立检索**的查询。

规则：
1. 把代词和指代补全成具体名词（「它」「这个」「那个方法」→ 实际名称）。
2. 把省略的限定补全（「那第二点呢」→ 上文第二点的具体主题）。
3. 如果原问题本身已经完整独立，就原样输出。
4. 只输出改写后的查询本身，不要解释、不要加引号、不要加前缀。
5. 用简体中文，尽量保留原文中的专有名词与命令。"""


def build_followup_prompt(query: str, context: str) -> str:
    """多轮对话中，当前这一轮的用户消息（带资料）。"""
    return USER_TEMPLATE.format(context=context, query=query)


# 附了图片时用的模板。
#
# 不能沿用纯 RAG 模板：它要求「只依据参考资料回答」，而用户附图的意图
# 主要是「看图」。实测直接用 RAG 模板会被框死，模型回答
# 「根据现有资料无法回答」—— 图片明明就在眼前。
IMAGE_TEMPLATE = """【随附图片】
（见本条消息中的图片）

【参考资料】
{context}

【问题】
{query}

请**优先依据图片内容**回答。如果参考资料中恰好有相关信息，
可以一并采用并用 [编号] 标注来源；资料无关时忽略它即可。
如果图片本身也没法确定，就直接说明，不要编造。"""


def build_image_prompt(query: str, context: str) -> str:
    """附图时的用户消息。"""
    return IMAGE_TEMPLATE.format(context=context, query=query)


# ---------------------------------------------------------------------------
# 不检索、直接回答
#
# 寒暄、致谢、与对话本身相关的问题、以及对已有内容做变换 —— 这些都不该
# 走 RAG。硬套 RAG 只会得到「根据现有资料无法回答」，既不自然也没意义。
# ---------------------------------------------------------------------------

DIRECT_SYSTEM_PROMPT = """你是一个友好、务实的助手，正在与用户对话。

规则：
1. 直接用你自己的知识回答，简洁自然，不要客套。
2. 不要声称"根据现有资料无法回答"——本轮并没有检索知识库。
3. 如果问题确实需要查具体的技术资料而你没有把握，可以**自然地**说明
   这一点，并建议用户把问题问得更具体一些，而不是生硬拒答。
4. 用简体中文回答。"""


def build_direct_prompt(query: str) -> str:
    """不检索时的用户消息。"""
    return query


def build_rag_prompt(query: str, context: str) -> str:
    """构造用户侧 prompt（单轮，等价于 build_followup_prompt）。"""
    return USER_TEMPLATE.format(context=context, query=query)


def build_messages(query: str, context: str) -> list[dict]:
    """OpenAI 格式的 messages。"""
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": build_rag_prompt(query, context)},
    ]


